/* ════════════════════════════════════════════════════════
   INVOKITPRO LICENCE SYSTEM
   Self-contained, server-free, tamper-evident.
   Keys are generated by the InvoKit Pro Licence Generator
   tool (separate file). Each key encodes the licensee's
   name, email, plan, issue date, and optional expiry.
   The HMAC checksum prevents key forgery or tampering.
   
   Distribution model:
   - You generate a unique key per buyer using the generator
   - The meta tag bkp-licence is set to "UNLICENSED" by default  
   - For a "clean" unlicensed file you distribute, the lock
     screen appears and the buyer enters their key
   - For a "pre-activated" file, set bkp-licence meta to the
     key and bkp-licensee to their name — app opens directly
   ════════════════════════════════════════════════════════ */

const BKP_SALT    = "InvoKitPro2024-xK9#mL2@vN7";
const BKP_UNREG_PREFIX = "UNREGISTERED-";
const BKP_ORG_KEY      = "invokitpro_lic_org";

const BKP_STORE_K = "bkp_lic_v2";

/* Decode a licence key → payload object or null */
function bkpDecode(key) {
  try {
    key = (key || '').trim().toUpperCase();
    if (!key.startsWith('BKP-')) return null;
    const parts = key.split('-');
    if (parts.length < 3) return null;
    const checksum  = parts[parts.length - 1];
    const b32part   = parts.slice(1, -1).join('-');
    const padding   = (8 - b32part.length % 8) % 8;
    const b32padded = b32part + '='.repeat(padding);
    // Base32 decode (A-Z 2-7)
    const B32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
    let bits = 0, bitsLen = 0, bytes = [];
    for (const ch of b32padded) {
      if (ch === '=') break;
      const v = B32.indexOf(ch);
      if (v < 0) return null;
      bits = (bits << 5) | v; bitsLen += 5;
      if (bitsLen >= 8) { bitsLen -= 8; bytes.push((bits >> bitsLen) & 0xFF); }
    }
    let payloadJson;
    if (typeof TextDecoder !== 'undefined') {
      payloadJson = new TextDecoder().decode(new Uint8Array(bytes));
    } else {
      // Fallback for older iOS: manual UTF-8 decode
      payloadJson = bytes.map(b => String.fromCharCode(b)).join('');
    }
    const payload = JSON.parse(payloadJson);
    // Verify HMAC checksum via SubtleCrypto (async — handled in bkpVerify)
    return { payload, payloadJson, checksum };
  } catch(e) { return null; }
}

