function bkpApplyLicence(payload) {
  // Hide lock screen and reveal app
  const lock = document.getElementById('bkp-lock');
  if (lock) lock.style.display = 'none';
  document.body.style.visibility = 'visible';
  // Show badge
  const badge     = document.getElementById('bkp-badge');
  const badgeName = document.getElementById('bkp-badge-name');
  if (badge && badgeName) {
    badgeName.textContent = payload.n;
    badge.style.display   = 'flex';
    const planDisplay = payload.p === 'annual' ? 'Annual (£25/yr)' : payload.p === 'lifetime' ? 'Lifetime (£60)' : payload.p;
    badge.title           = `Licensed to: ${payload.n}${payload.o ? ' — ' + payload.o : ''}\n${payload.e}\nPlan: ${planDisplay}\nIssued: ${payload.d}`;
  }
  // Store in global for other parts of app
  window._bkpLicence = payload;
  // Lock business name to licence org (supports first-time registration pool keys)
  if (payload.o) {
    const override = _getStoredOrgOverride();
    if (_isUnregisteredOrg(payload.o) && override) {
      _lockBusinessName(override);
    } else if (_isUnregisteredOrg(payload.o) && !override) {
      // Pool key: allow onboarding to set business name once, then lock it.
    } else {
      _lockBusinessName(payload.o);
    }
  }

  // Expiry enforcement
  if (payload._expired) {
    // Annual plan expired — block the app with renewal screen
    setTimeout(() => _bkpShowExpired(payload), 500);
  } else if (payload._daysLeft !== undefined && payload._daysLeft <= 7 && payload.p === 'annual') {
    // Annual plan expiring within 7 days — soft warning
    setTimeout(() => toast(`Your Annual licence expires in ${payload._daysLeft} day${payload._daysLeft===1?'':'s'}. Please renew soon.`,'er'), 2500);
  }
  // Show iOS install hint if on iOS Safari and not already installed
  setTimeout(_showIOSInstallHint, 3000);
}

function _lockBusinessName(orgName) {
  // Write org name into settings
  const stored = JSON.parse(localStorage.getItem('invokitpro_settings') || '{}');
  if (!stored.name) {
    // Only auto-fill if not already set
    stored.name = orgName;
    localStorage.setItem('invokitpro_settings', JSON.stringify(stored));
    const nameInput = document.getElementById('s-name');
    if (nameInput) nameInput.value = orgName;
  }
  // Lock the field visually
  const nameInput = document.getElementById('s-name');
  if (nameInput) {
    nameInput.readOnly = true;
    nameInput.style.cssText += ';background:var(--sur2);cursor:not-allowed;padding-right:32px;';
    nameInput.title = 'Business name is locked to your licence';
    nameInput.removeAttribute('oninput');
    nameInput.addEventListener('focus', () => toast('Business name is locked to your licence. Contact support to update.', 'er'));
    // Add padlock icon next to field
    const fg = nameInput.closest('.fg');
    if (fg && !fg.querySelector('.lock-icon')) {
      const lbl = fg.querySelector('label');
      if (lbl) lbl.innerHTML = 'Business Name <span class="lock-icon" title="Locked to licence" style="font-size:.75rem;color:var(--muted);">🔒</span>';
      const wrap = document.createElement('div');
      wrap.style.cssText = 'position:relative;';
      nameInput.parentNode.insertBefore(wrap, nameInput);
      wrap.appendChild(nameInput);
    }
  }
  // Save locked state so it persists across page loads
  localStorage.setItem('invokitpro_name_locked', '1');
  localStorage.setItem('invokitpro_name_locked_val', orgName);
}

function _restoreNameLock() {
  // Called on app load — re-apply lock if previously locked
  const locked = localStorage.getItem('invokitpro_name_locked');
  const val    = localStorage.getItem('invokitpro_name_locked_val');
  if (locked && val) _lockBusinessName(val);
}


function _isUnregisteredOrg(org) {
  return typeof org === 'string' && org.toUpperCase().startsWith(BKP_UNREG_PREFIX);
}
function _getStoredOrgOverride() {
  try { return (localStorage.getItem(BKP_ORG_KEY) || '').trim(); } catch(e) { return ''; }
}
function _setOrgOverride(org) {
  try { localStorage.setItem(BKP_ORG_KEY, org); } catch(e) {}
}
function _clearOrgOverride() {
  try { localStorage.removeItem(BKP_ORG_KEY); } catch(e) {}
}

function _enforceFirstTimeOrgRegistrationFromOnboarding() {
  const lic = window._bkpLicence;
  if (!lic || !lic.o) return true;
  if (_isUnregisteredOrg(lic.o) && !_getStoredOrgOverride()) {
    const name = (document.getElementById('ob-bname')?.value || '').trim();
    if (!name) {
      if (typeof toast === 'function') toast('Please enter your Business Name to complete activation.', 'er');
      document.getElementById('ob-bname')?.focus();
      return false;
    }
    _setOrgOverride(name);
    _lockBusinessName(name);
  }
  return true;
}



/* Activate flow — called when user submits key in lock screen */
async function bkpActivate() {
  const inp = document.getElementById('bkp-key-inp');
  const err = document.getElementById('bkp-err');
  if (!inp) return;
  const key = inp.value.trim();
  err.textContent = '';
  inp.classList.remove('er');
  if (!key) { err.textContent = 'Please enter your licence key.'; inp.classList.add('er'); return; }
  const btn = document.querySelector('.bkp-lock-btn');
  if (btn) { btn.textContent = 'Verifying…'; btn.disabled = true; }
  const payload = await bkpVerify(key);
  if (btn) { btn.textContent = 'Activate InvoKit Pro'; btn.disabled = false; }
  if (!payload) {
    err.textContent = 'Invalid or tampered licence key. Please check and try again.';
    inp.classList.add('er');
    inp.select();
    return;
  }
  bkpSaveLicence(key);
  bkpApplyLicence(payload);
  toast(`Welcome, ${payload.n}! InvoKit Pro activated ✓`, 'ok');
  // App is already fully initialised — bkpApplyLicence just hides the lock screen.
  // If first time (no onboarding done), show the onboarding wizard.
  if (!localStorage.getItem('ik_onboarded') || !_settings.name || !_settings.cur) {
    setTimeout(() => openOnboarding(), 400);
  }
}
window.bkpActivate = bkpActivate;

