/* Async HMAC verify — returns payload if valid, null if forged/tampered.
   Uses SubtleCrypto where available, falls back to pure-JS SHA-256 for Safari on file:// */
async function bkpVerify(key) {
  try {
    const decoded = bkpDecode(key);
    if (!decoded) return null;
    const { payload, payloadJson, checksum } = decoded;
    let hashHex;
    if (typeof crypto !== 'undefined' && crypto.subtle && window.location.protocol === 'https:') {
      const data    = new TextEncoder().encode(payloadJson + BKP_SALT);
      const hashBuf = await crypto.subtle.digest('SHA-256', data);
      hashHex = Array.from(new Uint8Array(hashBuf))
        .map(b => b.toString(16).padStart(2,'0')).join('').toUpperCase();
    } else {
      hashHex = _bkpSHA256(payloadJson + BKP_SALT).toUpperCase();
    }
    if (hashHex.slice(0, 8) !== checksum) return null;
    if (payload.x) {
      const expiry  = new Date(payload.x);
      const now     = new Date();
      const daysLeft = Math.ceil((expiry - now) / (1000*60*60*24));
      if (expiry < now) {
        // Lifetime plans never truly expire even if x is set
        if (payload.p === 'lifetime') return payload;
        return { ...payload, _expired: true, _daysLeft: daysLeft };
      }
      return { ...payload, _daysLeft: daysLeft };
    }
    return payload;
  } catch(e) {
    console.warn('[InvoKit] Licence verify error:', e);
    return null;
  }
}

/* Boot — runs at app start. Fail-CLOSED: any error shows lock screen, never opens app.
   Key priority: embedded meta tag → localStorage → lock screen. */
async function bkpBoot() {
  try {
    // 1. Pre-activated file: key baked into meta tag by licence generator
    const metaEl  = document.querySelector('meta[name="bkp-licence"]');
    const metaKey = metaEl ? metaEl.getAttribute('content') : '';
    if (metaKey && metaKey !== 'UNLICENSED') {
      const payload = await bkpVerify(metaKey);
      if (payload) { bkpApplyLicence(payload); return true; }
    }
    // 2. Previously activated — check sync stores first, then IDB fallback
    const storedKey = bkpLoadStoredKey();
    if (storedKey) {
      const payload = await bkpVerify(storedKey);
      if (payload) { bkpApplyLicence(payload); return true; }
      try { localStorage.removeItem(BKP_STORE_K); } catch(e) {}
      try { sessionStorage.removeItem(BKP_STORE_K); } catch(e) {}
    }
    // 2b. IDB fallback — catches file moves and renames
    const idbKey = await new Promise(res => bkpLoadFromIDB(res));
    if (idbKey && idbKey !== storedKey) {
      const payload = await bkpVerify(idbKey);
      if (payload) { bkpSaveLicence(idbKey); bkpApplyLicence(payload); return true; }
    }
    // 3. No valid licence — show lock screen
    _bkpShowLock();
    return false;
  } catch(e) {
    // Fail-closed: any unexpected error shows lock screen, never lets app through
    console.warn('[InvoKit] Licence boot error:', e);
    _bkpShowLock();
    return false;
  }
}

function _bkpShowLock() {
  document.body.style.visibility = 'visible';
  const lock = document.getElementById('bkp-lock');
  if (lock) {
    lock.style.display = 'flex';
    setTimeout(() => document.getElementById('bkp-key-inp')?.focus(), 150);
  }
}

/* Persist licence to localStorage */
function bkpSaveLicence(key) {
  try { localStorage.setItem(BKP_STORE_K, key); } catch(e) {}
  try { sessionStorage.setItem(BKP_STORE_K, key); } catch(e) {}
  try {
    const req = indexedDB.open('invokitpro_lic', 1);
    req.onupgradeneeded = e => e.target.result.createObjectStore('lic');
    req.onsuccess = e => {
      const tx = e.target.result.transaction('lic', 'readwrite');
      tx.objectStore('lic').put(key, 'key');
    };
  } catch(e) {}
  try {
    const exp = new Date(Date.now() + 1000*60*60*24*3650).toUTCString();
    document.cookie = `${BKP_STORE_K}=${encodeURIComponent(key)};expires=${exp};path=/;SameSite=Lax`;
  } catch(e) {}
}
function bkpLoadStoredKey() {
  try { const k = localStorage.getItem(BKP_STORE_K); if (k) return k; } catch(e) {}
  try { const k = sessionStorage.getItem(BKP_STORE_K); if (k) return k; } catch(e) {}
  try {
    const m = document.cookie.match(new RegExp('(?:^|;\\s*)' + BKP_STORE_K + '=([^;]+)'));
    if (m) return decodeURIComponent(m[1]);
  } catch(e) {}
  return null;
}
function bkpLoadFromIDB(cb) {
  try {
    const req = indexedDB.open('invokitpro_lic', 1);
    req.onupgradeneeded = e => e.target.result.createObjectStore('lic');
    req.onsuccess = e => {
      const tx = e.target.result.transaction('lic', 'readonly');
      const get = tx.objectStore('lic').get('key');
      get.onsuccess = () => cb(get.result || null);
      get.onerror   = () => cb(null);
    };
    req.onerror = () => cb(null);
  } catch(e) { cb(null); }
}

